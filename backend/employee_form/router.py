def _admin_rows():
    docs = list(forms.find({}).sort("updated_at", -1))
    kyc_docs = {d["empid"]: d for d in kyc_col.find({})}
    have = {d.get("empid") for d in docs}
    ids = [d.get("empid") for d in docs] + [e for e in kyc_docs if e not in have]
    names = {(e.get("EmpID") or "").strip().upper(): (e.get("Emp Name") or e.get("EmployeeName") or e.get("Name") or "")
             for e in employee_details_collection.find({"EmpID": {"$in": ids}})} if ids else {}
    rows = []
    for d in docs:
        data = d.get("data", {})
        p, c = data.get("personal", {}), data.get("contact", {})
        rows.append({
            "empid": d.get("empid"),
            "name": names.get(d.get("empid"), "") or " ".join(x for x in (p.get("first_name"), p.get("surname")) if x),
            "status": d.get("status", "draft"),
            "undertaking_status": d.get("undertaking_status", "draft"),
            "policy_status": d.get("policy_status", "draft"),
            "kyc_status": (kyc_docs.get(d.get("empid")) or {}).get("status", "none"),
            "email": c.get("email", ""), "mobile": c.get("present_mobile", ""),
            "submitted_at": _iso(d.get("submitted_at")), "updated_at": _iso(d.get("updated_at")),
            "edited_by": d.get("edited_by", ""),
        })
    for e in ids[len(docs):]:                                   # KYC filled, application form not started
        k = kyc_docs[e]
        x = k.get("data", {})
        rows.append({
            "empid": e, "name": names.get(e, "") or x.get("full_name", ""),
            "status": "none", "undertaking_status": "none", "policy_status": "none", "kyc_status": k.get("status", "draft"),
            "email": x.get("personal_email", ""), "mobile": x.get("mobile", ""),
            "submitted_at": None, "updated_at": _iso(k.get("updated_at")), "edited_by": "",
        })
    rows.sort(key=lambda r: r["updated_at"] or "", reverse=True)
    return rows


@router.get("/admin/list")
def admin_list(_: str = Depends(require_employee_form_admin)):
    return {"rows": _admin_rows()}


def _stamp(dt) -> str:
    return dt.strftime("%d/%m/%Y %H:%M") if isinstance(dt, datetime) else ""


def application_forms_xlsx(date_from: str = "", date_to: str = "", by: str = "updated_at", _: str = ""):
    """Excel of the application forms. Optional date range (IST days) on `by`: updated_at | submitted_at."""
    lo, hi = date_range.bounds(date_from, date_to)
    by = by if by in ("updated_at", "submitted_at") else "updated_at"
    from openpyxl import Workbook
    from openpyxl.styles import Alignment, Font, PatternFill

    heads = ["Emp Code", "Emp Name", "Status", "KYC Form", "Surname", "First Name", "Middle Name", "Sex", "Birth Date",
             "Nationality", "Marital Status", "PAN No.", "Aadhar No.", "E-Mail", "Emergency Contact",
             "Present Mobile", "Present Address", "Present City", "Present State", "Present Pin",
             "Permanent Address", "Present Employer", "Position", "Date of Joining", "Total CTC", "CTC Expected",
             "Submitted On (UTC)", "Last Updated (UTC)"]
    wb = Workbook()
    ws = wb.active
    ws.title = "Application Forms"
    ws.append(heads)
    for c in ws[1]:
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="2C3E50")
        c.alignment = Alignment(vertical="center")
    for d in forms.find({}).sort("empid", 1):
        if not date_range.within(d.get(by), lo, hi):
            continue
        x = d.get("data", {})
        p, c, e = x.get("personal", {}), x.get("contact", {}), x.get("present_employment", {})
        join = lambda *vals: ", ".join(v for v in vals if v)
        ws.append([
            d.get("empid"), _emp_name(d.get("empid")), d.get("status", "draft"),
            {"submitted": "Submitted", "draft": "Draft"}.get((kyc_col.find_one({"empid": d.get("empid")}) or {}).get("status"), "Not started"),
            p.get("surname"), p.get("first_name"), p.get("middle_name"), p.get("sex"), p.get("birth_date"),
            p.get("nationality"), p.get("marital_status"), p.get("pan_no"), p.get("aadhar_no"),
            c.get("email"), c.get("emergency_contact_no"), c.get("present_mobile"),
            join(c.get("present_address"), c.get("present_street"), c.get("present_landmark")),
            c.get("present_city"), c.get("present_state"), c.get("present_pin"),
            join(c.get("permanent_address"), c.get("permanent_street"), c.get("permanent_landmark"), c.get("permanent_city"),
                 c.get("permanent_state"), c.get("permanent_pin")),
            e.get("employer"), e.get("present_position"), e.get("date_of_joining"), e.get("total_ctc"), e.get("ctc_expected"),
            _stamp(d.get("submitted_at")), _stamp(d.get("updated_at")),
        ])
    for i, h in enumerate(heads, start=1):
        ws.column_dimensions[ws.cell(row=1, column=i).column_letter].width = max(len(h) + 2, 16)
    ws.freeze_panes = "A2"
    buf = BytesIO()
    wb.save(buf)
    return Response(content=buf.getvalue(),
                    media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                    headers={"Content-Disposition": "attachment; filename=Employee_Application_Forms.xlsx"})


def _copy_sheet(src, dst_wb, title: str) -> None:
    """Copy one worksheet (values, header look, widths, frozen row) into `dst_wb` as a new sheet."""
    from openpyxl.styles import Alignment, Font, PatternFill
    dst = dst_wb.create_sheet(title)
    for row in src.iter_rows(values_only=True):
        dst.append(list(row))
    for c in dst[1]:
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="2C3E50")
        c.alignment = Alignment(vertical="center")
    for key, dim in src.column_dimensions.items():
        if dim.width:
            dst.column_dimensions[key].width = dim.width
    dst.freeze_panes = src.freeze_panes


@router.get("/admin/export")
def admin_export_all(date_from: str = "", date_to: str = "", by: str = "updated_at", joiners_by: str = "created_at",
                     _: str = Depends(require_employee_form_admin)):
    """ONE Excel file with three sheets: Application Forms, KYC Details and New Joiners.
    The date range (IST days) applies to all three: `by` (updated_at | submitted_at) for the application forms,
    last-updated for the KYC sheet, `joiners_by` (created_at | last_login | last_activity) for the joiners."""
    from io import BytesIO as _B
    from openpyxl import Workbook, load_workbook
    from backend.kyc_form import router as kyc_router            # imported here: that module imports this one

    sheets = [("Application Forms", application_forms_xlsx(date_from, date_to, by)),
              ("KYC Details", kyc_router.admin_export(date_from, date_to, "updated_at", _)),
              ("New Joiners", admin_export_joiners(date_from, date_to, joiners_by, _))]
    wb = Workbook()
    wb.remove(wb.active)
    for title, resp in sheets:
        _copy_sheet(load_workbook(_B(resp.body)).active, wb, title)
    buf = BytesIO()
    wb.save(buf)
    return Response(content=buf.getvalue(),
                    media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                    headers={"Content-Disposition": "attachment; filename=Employee_Forms_KYC_and_New_Joiners.xlsx"})


