@router.delete("/admin/{empid}")
def admin_delete(empid: str, part: str = "all", admin: str = Depends(require_employee_form_admin)):
    """HR: delete a submitted form so the employee can fill and submit it again.
    part = application | undertaking | policy (that one form only) or all (the whole record)."""
    empid = _empid(empid)
    doc = forms.find_one({"empid": empid})
    if not doc:
        raise HTTPException(404, "No application form found for this employee")
    if part != "all" and part not in _PART_SECTIONS:
        raise HTTPException(400, "Unknown part")
    deleted_at = datetime.now(timezone.utc)
    employee_form_db["deleted_forms_log"].insert_one({   # audit trail: who deleted what, and when
        "empid": empid, "part": part, "deleted_by": _empid(admin), "deleted_at": deleted_at,
        "status_before": {k: doc.get(k) for k in ("status", "undertaking_status", "policy_status")}})
    if part == "all":
        forms.delete_one({"empid": empid})
        return {"success": True, "removed": "all"}
    status_key, sections = _PART_SECTIONS[part]
    data = doc.get("data", {})
    for sec in sections:
        if sec in data:
            data[sec] = [] if isinstance(data[sec], list) else {}
    unset = {status_key: "", status_key.replace("status", "submitted_at"): ""}
    if part == "application":
        unset["submitted_at"] = ""
    forms.update_one({"empid": empid}, {"$set": {"data": data, "updated_at": deleted_at}, "$unset": unset})
    left = forms.find_one({"empid": empid}) or {}
    if not any(left.get(k) for k in ("status", "undertaking_status", "policy_status")):
        forms.delete_one({"empid": empid})   # nothing left of this employee's record
    return {"success": True, "removed": part}

