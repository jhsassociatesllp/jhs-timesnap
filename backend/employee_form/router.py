@router.get("/admin/joiners/export")
def admin_export_joiners(date_from: str = "", date_to: str = "", by: str = "created_at",
                         _: str = Depends(require_employee_form_admin)):
    """Excel of the new-joiner logins. Optional date range (IST days) on `by`: created_at | last_login | last_activity."""
    lo, hi = date_range.bounds(date_from, date_to)
    by = by if by in ("created_at", "last_login", "last_activity") else "created_at"
    from openpyxl import Workbook
    from openpyxl.styles import Font, PatternFill

    heads = ["Personal Email", "Login ID", "Created On", "Password Last Set", "Email Sent", "Email Sent On", "Last Login",
             "Application Form", "Declaration & Undertaking", "Undertaking", "KYC Form", "Forms Submitted (of 4)", "Last Form Activity"]
    label = {"submitted": "Submitted", "draft": "Draft", "none": "Not started"}
    wb = Workbook()
    ws = wb.active
    ws.title = "New Joiners"
    ws.append(heads)
    for c in ws[1]:
        c.font = Font(bold=True, color="FFFFFF")
        c.fill = PatternFill("solid", fgColor="2C3E50")

    def stamp(iso):
        try:
            return datetime.fromisoformat(iso).strftime("%d/%m/%Y %H:%M") if iso else ""
        except Exception:
            return ""
    for r in joiner_rows():
        if not date_range.within(r.get(by), lo, hi):
            continue
        ws.append([r["email"], r["empid"], stamp(r["created_at"]), stamp(r["password_set_at"]),
                   {"sent": "Yes", "failed": "No (failed)", "none": "Not sent"}[r["mail"]], stamp(r["mail_at"]),
                   stamp(r["last_login"]) or "Never logged in", label.get(r["application"], r["application"]),
                   label.get(r["undertaking"], r["undertaking"]), label.get(r["policy"], r["policy"]), label.get(r["kyc"], r["kyc"]),
                   r["submitted_count"], stamp(r["last_activity"])])
    for i, h in enumerate(heads, start=1):
        ws.column_dimensions[ws.cell(row=1, column=i).column_letter].width = max(len(h) + 2, 18)
    ws.column_dimensions["A"].width = 34
    ws.freeze_panes = "B2"
    ws.auto_filter.ref = ws.dimensions
    buf = BytesIO()
    wb.save(buf)
    return Response(content=buf.getvalue(),
                    media_type="application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
                    headers={"Content-Disposition": "attachment; filename=New_Joiners.xlsx"})


