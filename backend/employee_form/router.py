@router.post("/admin/joiners")
def admin_create_joiners(payload: dict = Body(...), admin: str = Depends(require_employee_form_admin)):
    """One or many personal e-mails (list, or text separated by commas / spaces / new lines). A new e-mail gets a
    login; an e-mail that already has one gets a NEW password (forgotten-password case). Passwords are shown once."""
    raw = payload.get("emails", [])
    if isinstance(raw, str):
        raw = re.split(r"[\s,;]+", raw)
    emails, invalid, seen = [], [], set()
    for e in raw:
        e = str(e).strip().lower()
        if not e:
            continue
        if not _EMAIL_RE.match(e):
            invalid.append(e)
        elif e not in seen:
            seen.add(e)
            emails.append(e)
    if not emails and not invalid:
        raise HTTPException(400, "Please enter at least one e-mail address")
    if len(emails) > 500:
        raise HTTPException(400, "Please add at most 500 e-mails at a time")
    now = datetime.utcnow()
    results = []
    for e in emails:
        pw = _new_password()
        doc = joiners.find_one({"email": e})
        if doc:
            joiners.update_one({"_id": doc["_id"]}, {"$set": {"password_hash": _pwd.hash(pw), "password_set_at": now,
                              "failed": 0, "locked_until": None, "reset_by": _empid(admin)}})
            sessions_collection.delete_many({"employeeId": doc["empid"]})   # sessions of the old password end
            results.append({"email": e, "empid": doc["empid"], "password": pw, "status": "reset"})
        else:
            while True:
                empid = JOINER_PREFIX + secrets.token_hex(3).upper()
                if not joiners.find_one({"empid": empid}):
                    break
            joiners.insert_one({"email": e, "empid": empid, "password_hash": _pwd.hash(pw), "created_at": now,
                                "password_set_at": now, "created_by": _empid(admin), "failed": 0, "locked_until": None})
            results.append({"email": e, "empid": empid, "password": pw, "status": "created"})
    # Every joiner is e-mailed the link and login (Microsoft Graph). A mail problem never undoes the logins just
    # made: the result says who did not get one, so HR can share the password by hand.
    try:
        mail = joiner_mail.send_logins(results)
    except Exception as exc:
        mail = {"configured": True, "sent": [], "failed": [r["email"] for r in results],
                "error": f"Could not send the e-mails: {str(exc)[:160]}"}
    failed = set(mail.get("failed") or [])
    for r in results:
        joiners.update_one({"email": r["email"]}, {"$set": {"last_mail": {"at": datetime.utcnow(), "ok": r["email"] not in failed}}})
    return {"results": results, "invalid": invalid, "mail": mail}


def joiner_rows() -> list:
    """One row per new-joiner login, with everything HR needs to follow the onboarding up."""
    docs = list(joiners.find({}).sort("created_at", -1))
    by_emp = {d["empid"]: d for d in forms.find({"empid": {"$in": [j["empid"] for j in docs]}})} if docs else {}
    kyc_by = {d["empid"]: d for d in kyc_col.find({"empid": {"$in": [j["empid"] for j in docs]}})} if docs else {}
    rows = []
    for j in docs:
        f = by_emp.get(j["empid"]) or {}
        k = kyc_by.get(j["empid"]) or {}
        parts = {"application": f.get("status", "none"), "undertaking": f.get("undertaking_status", "none"),
                 "policy": f.get("policy_status", "none"), "kyc": k.get("status", "none") if k else "none"}
        mail = j.get("last_mail") or {}
        rows.append({
            "email": j["email"], "empid": j["empid"], "created_at": _iso(j.get("created_at")),
            "password_set_at": _iso(j.get("password_set_at")), "last_login": _iso(j.get("last_login")),
            "mail": ("sent" if mail.get("ok") else "failed") if mail else "none", "mail_at": _iso(mail.get("at")),
            "application": parts["application"], "undertaking": parts["undertaking"], "policy": parts["policy"],
            "kyc": parts["kyc"],
            "form": parts["application"],                       # kept for older pages
            "submitted_count": sum(1 for v in parts.values() if v == "submitted"),
            "last_activity": max([x for x in (_iso(f.get("updated_at")), _iso(k.get("updated_at"))) if x], default=None),
            "submitted_at": _iso(f.get("submitted_at")),
        })
    return rows


